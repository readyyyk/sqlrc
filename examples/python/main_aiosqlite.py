class UserQueries:
    def __init__(self, pool):
        self.pool = pool
        
    async def create_user(self, params: CreateUserParams) -> Optional[CreateUserResult]:
        async with self.pool.acquire() as conn:
            query = """
            INSERT INTO users (username, email, password_hash, role, is_active)
            VALUES (?, ?, ?, ?, ?)
            RETURNING id, username, email, role, is_active, created_at, updated_at
            """
            row = await conn.fetchone(query, 
                params.username, params.email, params.password_hash, 
                params.role, params.is_active)
            
            if row is None:
                return None
                
            return CreateUserResult(
                id=row[0],
                username=row[1],
                email=row[2],
                role=row[3],
                is_active=row[4],
                created_at=row[5],
                updated_at=row[6]
            )
            
    async def get_user_by_id(self, params: GetUserByIdParams) -> Optional[Dict[str, Any]]:
        async with self.pool.acquire() as conn:
            query = """
            SELECT id, username, email, role, is_active, created_at, updated_at
            FROM users
            WHERE id = ?
            """
            row = await conn.fetchone(query, params.user_id)
            
            if row is None:
                return None
                
            return {
                'id': row[0],
                'username': row[1],
                'email': row[2],
                'role': row[3],
                'is_active': row[4],
                'created_at': row[5],
                'updated_at': row[6]
            }
            
    async def delete_user(self, params: DeleteUserParams) -> None:
        async with self.pool.acquire() as conn:
            query = "DELETE FROM users WHERE id = ?"
            await conn.execute(query, params.user_id)
            return None

async def initialize_database(db_path: str):
    # Remove existing database if it exists
    if os.path.exists(db_path):
        os.remove(db_path)
    
    # Read schema.sql file
    with open(os.path.join(os.path.dirname(__file__), "..", "schema.sql"), "r") as f:
        schema_sql = f.read()
    
    # Create a new database and execute the schema
    async with aiosqlite.connect(db_path) as conn:
        await conn.executescript(schema_sql)

